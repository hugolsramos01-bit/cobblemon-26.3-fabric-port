package com.cobblemon.mod.common.mixin;

import com.cobblemon.mod.common.client.render.item.CobblemonBuiltinItemRendererRegistry;
import net.minecraft.client.renderer.item.ItemModelResolver;
import net.minecraft.client.renderer.item.ItemStackRenderState;
import net.minecraft.world.entity.ItemOwner;
import net.minecraft.world.item.ItemDisplayContext;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.Level;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(ItemModelResolver.class)
public class BuiltinModelItemRendererMixin {

    @Inject(
        method = "updateForTopItem(Lnet/minecraft/client/renderer/item/ItemStackRenderState;Lnet/minecraft/world/item/ItemStack;Lnet/minecraft/world/item/ItemDisplayContext;Lnet/minecraft/world/level/Level;Lnet/minecraft/world/entity/ItemOwner;I)V",
        at = @At("HEAD"),
        cancellable = true
    )
    private void cobblemon$extractDynamicItemRenderer(ItemStackRenderState renderState, ItemStack stack, ItemDisplayContext mode, Level level, ItemOwner owner, int seed, CallbackInfo ci) {
        if (CobblemonBuiltinItemRendererRegistry.extract(stack, mode, renderState)) {
            ci.cancel();
        }
    }

}
