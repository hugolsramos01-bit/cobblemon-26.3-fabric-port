package com.cobblemon.mod.common.mixin.client;

import com.cobblemon.mod.common.client.render.ClientPlayerIcon;
import com.cobblemon.mod.common.entity.pokemon.PokemonEntity;
import net.minecraft.client.renderer.entity.player.AvatarRenderer;
import net.minecraft.client.renderer.entity.state.AvatarRenderState;
import net.minecraft.world.entity.Avatar;
import net.minecraft.world.entity.player.Player;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(AvatarRenderer.class)
public abstract class PlayerRendererMixin {

    @Inject(
            method = "extractRenderState(Lnet/minecraft/world/entity/Avatar;Lnet/minecraft/client/renderer/entity/state/AvatarRenderState;F)V",
            at = @At("TAIL")
    )
    private void cobblemon$adjustMountedAvatarAndQueueIcon(
            Avatar entity,
            AvatarRenderState renderState,
            float partialTick,
            CallbackInfo ci
    ) {
        if (!(entity instanceof Player player)) {
            return;
        }

        if (player.isPassenger() && player.getVehicle() instanceof PokemonEntity) {
            // AvatarRenderer.getRenderOffset and the player model both consume this state later.
            renderState.isCrouching = false;
        }

        ClientPlayerIcon.Companion.onRenderPlayer(player);
    }
}
